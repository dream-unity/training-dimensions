export function getLifePurposeExampleMap(level: number): LifePurposeExampleMap {
  const safe = Math.max(1, Math.min(12, Math.round(level))) as LifePurposeExampleLevel
  return LIFE_PURPOSE_EXAMPLE_MAPS[safe - 1]
}

export function validateLifePurposeExampleMap(map: LifePurposeExampleMap): string[] {
  const errors: string[] = []
  const nodeIds = new Set(map.nodes.map((node) => node.id))
  if (!nodeIds.has(map.rootId)) errors.push('Root node is missing.')
  if (nodeIds.size !== map.nodes.length) errors.push('Node ids must be unique.')
  const edgeIds = new Set(map.edges.map((edge) => edge.id))
  if (edgeIds.size !== map.edges.length) errors.push('Edge ids must be unique.')
  map.nodes.forEach((node) => {
    if (node.stage < 1 || node.stage > map.stages.length) errors.push(`Node ${node.id} has an invalid stage.`)
  })
  map.edges.forEach((edge) => {
    if (!nodeIds.has(edge.from) || !nodeIds.has(edge.to)) errors.push(`Edge ${edge.id} points to a missing node.`)
    if (edge.from === edge.to) errors.push(`Edge ${edge.id} cannot connect a node to itself.`)
    if (edge.stage < 1 || edge.stage > map.stages.length) errors.push(`Edge ${edge.id} has an invalid stage.`)
  })
  return errors
}
